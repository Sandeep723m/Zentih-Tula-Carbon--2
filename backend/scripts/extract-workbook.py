# Regenerates src/calc/workbookData.ts from the calculation engine workbook (tabs 02 and 04), so the
# reference data is the workbook's own rows, not a retyped copy. Example rows (EG-) are skipped.
#   python3 -I scripts/extract-workbook.py "<workbook>.xlsx" src/calc/workbookData.ts   (needs openpyxl)
import datetime, decimal, json, re, sys
import openpyxl

wb = openpyxl.load_workbook(sys.argv[1], data_only=True)

def rows(sheet, cols):
    for r in wb[sheet].iter_rows(min_row=7, values_only=True):
        if r[0] and not str(r[0]).startswith('EG'):
            yield {k: (v.date().isoformat() if isinstance(v, datetime.datetime) else v) for k, v in zip(cols, r)}

def txt(v):
    return None if v is None else (format(decimal.Decimal(repr(v)).normalize(), 'f') if isinstance(v, float) else str(v).strip())

acts = [{k: txt(v) for k, v in a.items()} for a in rows('02 Activity Types', ['code', 'name', 'scope', 'category', 'measuredIn', 'carbonOrigin', 'isRemoval', 'dataSource', 'notes'])]
# Tab 02 has no NCV or density column: the SME quoted them in the notes ("NCV 43 GJ/t (0.043 TJ/t); density
# 0.84 kg/L"). They are read here, once, into structured fields, so the application never parses text. Every
# combustion row must yield an NCV, or the import stops: a missing value is a workbook gap, never a silent guess.
NCV = re.compile(r'NCV (?:for [^0-9]*)?([\d.]+) GJ/t')
DENSITY = re.compile(r'density (?:about )?([\d.]+) (kg/[lL]|kg/m3)')
for a in acts:
    notes = a['notes'] or ''
    ncv = NCV.search(notes)
    dens = DENSITY.search(notes)
    a['ncvGJPerT'] = ncv.group(1) if ncv else None
    a['density'] = dens.group(1) if dens else None
    a['densityUnit'] = ('kg/l' if dens.group(2).lower() == 'kg/l' else 'kg/m3') if dens else None
    if a['category'] in ('Stationary combustion', 'Mobile combustion') and not a['ncvGJPerT']:
        sys.exit(f"{a['code']}: combustion activity with no NCV in its tab 02 notes")

facs = [{k: txt(v) for k, v in f.items()} for f in rows('04 Factor Library', ['code', 'activityCode', 'gas', 'value', 'numeratorUnit', 'denominatorUnit', 'carbonOrigin', 'source', 'sourceVersion', 'validFrom', 'validTo', 'geography', 'tier', 'notes'])]

# AR5 GWPs of refrigerants are quoted in the AR6 rows' notes ("AR5 value 1923.5"): a structured field too.
for f in facs:
    m = re.search(r'AR5 value ([\d.]+)', f['notes'] or '')
    f['ar5Value'] = m.group(1) if m and (f['sourceVersion'] or '').startswith('AR6') else None

with open(sys.argv[2], 'w') as out:
    out.write('// GENERATED by scripts/extract-workbook.py from TC-DOM-002a Calculation Engine Workbook v0.1\n')
    out.write('// (Scope 1-2 fill), tabs 02 and 04, verbatim. Do not edit; rerun the script.\n')
    out.write('export const WORKBOOK_ACTIVITY_TYPES = ' + json.dumps(acts, indent=1, ensure_ascii=False) + ' as const\n\n')
    out.write('export const WORKBOOK_FACTORS = ' + json.dumps(facs, indent=1, ensure_ascii=False) + ' as const\n')
print(len(acts), 'activity types,', len(facs), 'factors')
