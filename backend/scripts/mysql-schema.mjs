// Builds prisma-mysql/schema.prisma from the PostgreSQL schema, which stays the single source of truth.
// MySQL's default String column is VARCHAR(191), so fields the API allows to be longer are widened here.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const WIDEN = {
  'Organization.name': '@db.VarChar(255)', 'Organization.legalName': '@db.VarChar(255)',
  'Organization.statusReason': '@db.Text', 'Organization.address': '@db.Text',
  'Facility.name': '@db.VarChar(255)', 'Facility.address': '@db.Text',
  'EmissionSource.name': '@db.VarChar(255)',
  'User.email': '@db.VarChar(255)', 'User.name': '@db.VarChar(255)',
  'ActivityRecord.notes': '@db.Text',
  'AuditLog.reason': '@db.Text',
  'SubscriptionEvent.reason': '@db.Text',
  'OrgBoundary.changeReason': '@db.Text',
  'EmissionFactor.source': '@db.VarChar(300)', 'EmissionFactor.geography': '@db.VarChar(255)', 'EmissionFactor.notes': '@db.Text',
  'CalculationResult.confirmationReason': '@db.Text',
  'ActivityType.notes': '@db.Text', 'CalculationRun.gwpReason': '@db.Text',
  'ActivityRecord.returnReason': '@db.Text', 'ActivityReview.comment': '@db.Text', 'PeriodLockEvent.reason': '@db.Text',
  'VerificationQuery.subject': '@db.VarChar(255)', 'VerificationQueryMessage.body': '@db.Text',
  'IntakeDocument.fileName': '@db.VarChar(255)', 'IntakeDocument.errorMessage': '@db.Text',
  'EmissionFactor.withdrawnReason': '@db.Text', 'EmissionFactor.basis': '@db.Text', 'EmissionFactor.approvalNote': '@db.Text', 'EmissionFactor.evidenceName': '@db.VarChar(255)',
  'UnitRequest.reason': '@db.Text', 'UnitRequest.resolution': '@db.Text',
  'FuelProperty.certificateRef': '@db.VarChar(255)', 'FuelProperty.notes': '@db.Text', 'FuelProperty.reviewNote': '@db.Text',
}

let model = null
const seen = new Set()
const out = readFileSync('prisma/schema.prisma', 'utf8').split('\n').map((line) => {
  const m = line.match(/^model (\w+)/)
  if (m) model = m[1]
  if (line.startsWith('}')) model = null
  if (line.includes('provider = "postgresql"')) return line.replace('postgresql', 'mysql')
  const field = line.match(/^(\s+)(\w+)(\s+)(String\??)(.*)$/)
  const attr = field && WIDEN[`${model}.${field[2]}`]
  if (!attr) return line
  seen.add(`${model}.${field[2]}`)
  const [, indent, name, gap, type, rest] = field
  return `${indent}${name}${gap}${type} ${attr}${rest}`
})

const missing = Object.keys(WIDEN).filter((k) => !seen.has(k))
if (missing.length) throw new Error(`mysql-schema: fields not found in schema.prisma: ${missing.join(', ')}`)

mkdirSync('prisma-mysql', { recursive: true })
writeFileSync('prisma-mysql/schema.prisma', `// GENERATED by scripts/mysql-schema.mjs from prisma/schema.prisma. Do not edit.\n${out.join('\n')}`)
console.log('prisma-mysql/schema.prisma written')
