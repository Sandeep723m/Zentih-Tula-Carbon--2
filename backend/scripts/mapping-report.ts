// Writes docs/activity-factor-formula-map.md from the code and the workbook seed: for every tab 02 activity, its
// tab 06 formula, the tab 04 factors in force for FY2024-25, units, NCV and density, required site or supplier
// inputs, validation rules, and whether it can be calculated. Regenerate after changing reference data.
//   npx tsx scripts/mapping-report.ts
import { writeFileSync } from 'node:fs'
import { allowedShapes } from '../src/calc/core/factorRules.js'
import { isCalculable } from '../src/calc/registry.js'
import { ACTIVITY_TYPES, SEED_FACTORS } from '../src/calc/referenceData.js'

const FY = '2024-04-01'
const inForce = (code: string) => SEED_FACTORS.filter((f) => f.activityCode === code && f.validFrom <= FY && (!f.validTo || f.validTo >= FY))
const RULES: Record<string, string> = {
  'C-01': 'V-01, V-02, V-03, V-04, V-06, V-09, V-10, V-11, V-14, V-16, V-17, J-04, FP-01/02',
  'C-02': 'as C-01; biogenic CO2 memo (G-05); AR5 blocked (no AR5 non-fossil CH4)',
  'C-03': 'as C-01, plus C-15 (distance ÷ fuel economy)',
  'C-04': 'V-01, V-03, V-16; factor choice per plant type',
  'C-05': 'V-01, V-03, V-15, V-16, J-07 (screening)',
  'C-06': 'V-01, V-03, V-04, V-16, V-18, rule 9 fallback; C-07 alongside (V-13)',
  'C-08': 'V-08 (meter reference), J-05 (end use)',
  'C-21': 'V-19 (supplier factor), R-11 (confirmation)',
}
const INPUTS: Record<string, string> = {
  'C-01': 'density for volumes (record → monthly register → default with confirmation); optional lab NCV, CO2 factor, carbon content; blend share',
  'C-02': 'as C-01', 'C-03': 'as C-01; fuel economy for distances',
  'C-04': 'plant type / factor choice; abated fraction', 'C-05': 'disposed and recovered kg, or charge and leak rate',
  'C-06': 'facility grid region', 'C-08': 'metered tonnes and meter reference (site-measured)',
  'C-21': 'supplier factor (record, or the organisation\'s own library factor): supplier-specific',
}
const lines = [
  '# Activity → factor → formula map',
  '',
  'Generated by `backend/scripts/mapping-report.ts` from workbook TC-DOM-002a v0.1 (tabs 02, 04, 06) as loaded in the engine. Factors listed are those in force on 1 April 2024 (FY2024-25). "Gap" marks an activity the engine blocks (V-03) because the workbook has no value: it is never estimated.',
  '',
  '| Activity | Name | Category | Formula | Factors in force (gas: code) | Factor shape accepted | Units | Default NCV / density | Required site or supplier inputs | Validation | Status |',
  '|---|---|---|---|---|---|---|---|---|---|---|',
]
for (const a of ACTIVITY_TYPES) {
  const f = inForce(a.code)
  const byGas = [...new Set(f.map((x) => x.gas))].map((g) => `${g}: ${f.filter((x) => x.gas === g).map((x) => x.code).join(', ')}`).join('; ')
  const combustion = ['C-01', 'C-02', 'C-03'].includes(a.formulaCode ?? '')
  const gap = combustion ? !['CO2', 'CH4', 'N2O'].every((g) => f.some((x) => x.gas === g))
    : a.formulaCode === 'C-05' ? !f.some((x) => x.gas === 'CO2e') : a.formulaCode === 'C-04' ? f.length === 0 : false
  const status = !a.formulaCode ? (a.code === 'A-PPA' ? 'instrument factor for C-07' : 'not calculated (Phase 2 / no formula)')
    : !isCalculable(a.formulaCode) ? 'NO METHOD' : gap ? 'Gap: blocked (V-03)' : 'calculable'
  const shapes = allowedShapes(a).map((s) => `${s.gas} ${s.numeratorUnit}/${s.denominatorUnit}`)
  const props = [a.defaultNcvPublished ? `NCV ${a.defaultNcvPublished}` : '', a.defaultDensity ? `ρ ${a.defaultDensity} ${a.defaultDensityUnit}` : ''].filter(Boolean).join('; ')
  lines.push(`| ${a.code} | ${a.name} | ${a.category} | ${a.formulaCode ?? '—'} | ${byGas || '—'} | ${shapes.length > 4 ? `${shapes.slice(0, 4).join('; ')} …` : shapes.join('; ') || '—'} | ${(a.allowedUnits as string[]).join(', ') || 'any'} | ${props || '—'} | ${a.formulaCode ? INPUTS[a.formulaCode] ?? '' : ''} | ${a.formulaCode ? RULES[a.formulaCode] ?? '' : ''} | ${status} |`)
}
const count = (s: string) => lines.filter((l) => l.endsWith(`| ${s} |`)).length
lines.push('', `Totals: ${ACTIVITY_TYPES.length} activities; ${count('calculable')} calculable; ${lines.filter((l) => l.includes('Gap: blocked')).length} blocked by workbook gaps; ${lines.filter((l) => l.includes('not calculated')).length} not calculated (Phase 2 / no formula); ${count('NO METHOD')} without a method.`)
writeFileSync('../docs/activity-factor-formula-map.md', lines.join('\n') + '\n')
console.log(lines.at(-1))
